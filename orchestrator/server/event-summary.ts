/**
 * One line for the entry, for the Activity page and the log's list: "Lee Lead set up the orchestrator",
 * "System merged request #4". A kind this list does not know is said with its detail, which the
 * log keeps redacted and already written as what was done.
 */
export function eventSummary(event: Pick<OrchestratorEvent, "kind" | "actor" | "subject" | "detail">): string {
  const who = event.actor.kind === "orchestrator" ? "System" : event.actor.name || event.actor.email || "Someone";
  const done = DONE[event.kind];
  if (!done) return `${who} ${event.detail}`;
  const number = event.kind.startsWith("request.") ? /^request:(\d+)$/.exec(event.subject ?? "")?.[1] : undefined;
  return `${who} ${number ? done.replace("a request", `request #${number}`) : done}`;
}
