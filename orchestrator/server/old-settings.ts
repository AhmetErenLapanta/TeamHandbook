/** The settings it read by building the name, one per sign-in provider or forge. */
const OLD_FAMILIES = ["CONSOLE_SIGN_IN_", "CONSOLE_FORGE_GITHUB_", "CONSOLE_FORGE_GITLAB_"];

const isOld = (name: string) => OLD_NAMES.has(name) || OLD_FAMILIES.some((family) => name.startsWith(family));

/** The settings in `env` still under their old name, each with the name it has now. */
export function oldSettings(env: NodeJS.ProcessEnv = process.env): { old: string; now: string }[] {
  return Object.keys(env)
    .filter(isOld)
    .sort()
    .map((old) => ({ old, now: old.replaceAll("CONSOLE", "ORCHESTRATOR") }));
}

/** Why this start stops, or null when no setting has its old name. */
export function oldSettingsRefused(env: NodeJS.ProcessEnv = process.env): string | null {
  const found = oldSettings(env);
  if (!found.length) return null;
  return `${found.map(({ old, now }) => `${old} is now ${now}`).join("; ")}; rename ${found.length === 1 ? "it" : "them"} where ${found.length === 1 ? "it is" : "they are"} set, and this orchestrator stops until then`;
}
