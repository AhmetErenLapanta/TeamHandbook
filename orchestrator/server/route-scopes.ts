export type RouteKey = keyof typeof ROUTE_SCOPES;

/** What the route registered as `method` and `pattern` takes, or undefined for one the table does not hold. */
export function routeNeed(method: string, pattern: string): RouteNeed | undefined {
  return (ROUTE_SCOPES as Record<string, RouteNeed>)[`${method} ${pattern}`];
}

/**
 * Registers a route by its row: a new route is written `route(app, "POST /api/things", handler)`,
 * and one whose row is missing from ROUTE_SCOPES does not type-check. Routes from before this
 * helper keep their plain registrations; the test gate covers those.
 */
export function route<E extends Env>(app: Hono<E>, key: RouteKey, ...handlers: H<E>[]): void {
  const [method, path] = key.split(" ") as [string, string];
  (app.on as (method: string, path: string, ...handlers: H<E>[]) => unknown)(method, path, ...handlers);
}
